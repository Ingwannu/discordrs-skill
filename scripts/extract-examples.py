#!/usr/bin/env python3
"""Extract the ```rust blocks of the skill into scratch crates, one per feature set.

Every ```rust block in SKILL.md and references/*.md must start with a line
`// features: a, b` (Cargo features added to discordrs' defaults) or
`// features: default`. Blocks with the same set go into one crate under
<out>/<set-name>/, each block wrapped in its own module, so `cargo check` in
that crate proves the blocks compile against the requested discordrs version
with exactly the features they claim.

Usage: extract-examples.py <skill-root> <out-dir> <discordrs-dependency-spec>
The dependency spec is TOML for the discordrs table minus `features`, e.g.
`version = "=3.1.0"` or `path = "/home/me/discord.rs"`.

[Decision Log]
- 목적과 의도: 스킬 문서의 모든 Rust 예제가 배포된 크레이트에서 실제로 컴파일되는지 기계적으로 확인한다.
- 기존 구현 및 제약 조건: 2.x 스킬 예제는 손으로만 검증했고, 3.0은 타입이 대부분 바뀌어 기억에 의존한 예제가 틀리기 쉽다.
  예제마다 필요한 feature가 다르다(gateway, interactions, voice, sharding).
- 검토한 주요 대안: (1) 전체 feature 한 번 컴파일, (2) 예제를 별도 .rs 파일로 두고 문서에 include, (3) 문서에서 추출 +
  feature 집합별 크레이트.
- 선택한 방식: (3). 블록 첫 줄의 `// features:` 주석이 필요한 feature를 밝히고, 같은 집합끼리 한 크레이트로 묶는다.
- 다른 대안 대신 이 방식을 선택한 이유: (1)은 예제가 주장하는 feature가 부족해도 통과한다. (2)는 문서가 마크다운
  그대로 읽히지 않는다(스킬은 에이전트가 파일을 직접 읽는다). (3)은 문서가 원본이고, feature 주석이 독자에게도 정보가 된다.
- 장점, 단점 및 영향: feature 집합 수만큼 discordrs를 다시 검사한다(집합당 20~45초). 블록은 완결된 item이어야 하므로
  문장 조각(`rest.get_x().await?;`)은 함수로 감싸야 한다.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

FENCE = re.compile(r"^```(\S*)\s*$")
FEATURES = re.compile(r"^//\s*features:\s*(.+?)\s*$")
KNOWN = {
    "cache", "gateway", "collectors", "sharding", "zstd-stream", "voice",
    "voice-encode", "dave", "interactions",
}

CARGO_TOML = """[package]
name = "{name}"
version = "0.0.0"
edition = "2021"
publish = false

[dependencies]
discordrs = {{ {spec}, features = [{features}] }}
serde = {{ version = "1", features = ["derive"] }}
serde_json = "1"
tokio = {{ version = "1", features = ["full"] }}
axum = "0.8"
"""

LIB_HEADER = """// Generated by scripts/extract-examples.py; do not edit.
// Examples must not use deprecated APIs or leave warnings; they need not be called.
#![deny(warnings)]
#![allow(dead_code)]
"""


def blocks(path: Path):
    lines = path.read_text(encoding="utf-8").splitlines()
    inside, lang, start, body = False, "", 0, []
    for number, line in enumerate(lines, 1):
        match = FENCE.match(line)
        if not inside and match and match.group(1):
            inside, lang, start, body = True, match.group(1), number, []
        elif inside and line.strip() == "```":
            inside = False
            if lang == "rust":
                yield start, body
        elif inside:
            body.append(line)
    if inside:
        raise SystemExit(f"{path}:{start}: unterminated code fence")


def main() -> int:
    if len(sys.argv) != 4:
        print(__doc__.split("\n\n")[2], file=sys.stderr)
        return 2
    root, out, spec = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3]
    sources = [root / "SKILL.md", *sorted((root / "references").glob("*.md"))]
    groups: dict[tuple[str, ...], list[tuple[str, int, list[str]]]] = {}
    errors = []
    for source in sources:
        for start, body in blocks(source):
            where = f"{source.relative_to(root)}:{start}"
            match = FEATURES.match(body[0]) if body else None
            if not match:
                errors.append(f"{where}: first line must be `// features: ...`")
                continue
            names = tuple(sorted({f.strip() for f in match.group(1).split(",")} - {"default"}))
            unknown = [f for f in names if f not in KNOWN]
            if unknown:
                errors.append(f"{where}: unknown features {unknown}")
                continue
            groups.setdefault(names, []).append((where, start, body))
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    out.mkdir(parents=True, exist_ok=True)
    for names, items in sorted(groups.items()):
        name = "check-" + ("-".join(names) if names else "default")
        crate = out / name
        (crate / "src").mkdir(parents=True, exist_ok=True)
        features = ", ".join(f'"{f}"' for f in names)
        (crate / "Cargo.toml").write_text(CARGO_TOML.format(name=name, spec=spec, features=features))
        parts = [LIB_HEADER]
        for index, (where, _start, body) in enumerate(items):
            parts.append(f"\n// {where}\nmod example_{index:02} {{\n")
            parts.extend(f"    {line}\n" if line else "\n" for line in body)
            parts.append("}\n")
        (crate / "src" / "lib.rs").write_text("".join(parts))
        print(f"{name}\t{len(items)} block(s)\t{', '.join(w for w, _, _ in items)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
